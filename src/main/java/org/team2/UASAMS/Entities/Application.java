package org.team2.UASAMS.Entities;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

import org.team2.UASAMS.Entities.Enums.ApplicationStatus;

import jakarta.persistence.*;
import lombok.*;

/**
 * Represents an application to a scholarship within the UASAMS system.
 * <p>
 * The application stores the status as an ENUM and keeps track of its submission dates. 
 * Acts as the middle man connecting the student, scholarship, submitted documents, answers, 
 * reviews, and award selection.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link StudentUser} – The student who submitted the application</li>
 *   <li>{@link Scholarship} – The scholarship being applied for</li>
 *   <li>{@link ApplicationDocument} – Supporting files uploaded by the student</li>
 *   <li>{@link ApplicationAnswer} – Responses to the scholarship's application questions</li>
 *   <li>{@link ApplicationReview} – Reviewer scores and feedback</li>
 *   <li>{@link AwardSelection} – Award decision if the application is selected</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class Application {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Date and time when the student submitted the application.
     */
    private LocalDateTime submissionDate;

    /**
     * Current stage of the application (e.g., DRAFT, SUBMITTED, UNDER_REVIEW, APPROVED).
     */
    @Enumerated(EnumType.STRING)
    private ApplicationStatus status;

    /**
     * The scholarship this application is for.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "scholarship_id", nullable = false)
    private Scholarship scholarship;

    /**
     * The student who owns and submitted this application.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "student_user_id", nullable = false)
    private StudentUser studentUser;

    /**
     * Reviewer evaluations tied to this application.
     */
    @OneToMany(mappedBy = "application", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<ApplicationReview> reviews = new ArrayList<>();

    /**
     * Supporting documents uploaded for this application.
     */
    @OneToMany(mappedBy = "application", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<ApplicationDocument> documents = new ArrayList<>();

    /**
     * Answers submitted for the scholarship's prompt questions.
     */
    @OneToMany(mappedBy = "application", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<ApplicationAnswer> answers = new ArrayList<>();

    /**
     * Final award record if this application wins the scholarship.
     */
    @OneToOne(mappedBy = "application", cascade = CascadeType.ALL)
    private AwardSelection awardSelection;
}