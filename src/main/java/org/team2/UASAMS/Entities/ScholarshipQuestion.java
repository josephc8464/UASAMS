package org.team2.UASAMS.Entities;

import jakarta.persistence.*;
import lombok.*;

import java.util.ArrayList;
import java.util.List;

import org.team2.UASAMS.Entities.Enums.ScholarshipQuestionInputType;

/**
 * Represents a custom prompt or question attached to a scholarship application within the UASAMS system.
 * <p>
 * Defines the question text, whether an answer is mandatory, and the expected input format
 * via {@link ScholarshipQuestionInputType}. Links back to the parent {@link Scholarship} and tracks
 * all student {@link ApplicationAnswer} responses submitted for it.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link Scholarship} – The scholarship this question belongs to</li>
 *   <li>{@link ApplicationAnswer} – Student responses submitted for this question</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class ScholarshipQuestion {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The prompt or question text displayed to applicants.
     */
    @Column(columnDefinition = "TEXT")
    private String questionText;

    /**
     * Indicates whether applicants must answer this question before submitting.
     */
    private boolean isRequired;

    /**
     * Expected format for the response (e.g., TEXT, NUMBER, FILE, ENUM).
     */
    @Enumerated(EnumType.STRING)
    private ScholarshipQuestionInputType inputType;

    /**
     * The scholarship that owns this question.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    private Scholarship scholarship;

    /**
     * All student answers submitted in response to this question.
     */
    @OneToMany(mappedBy = "question", cascade = CascadeType.ALL)
    private List<ApplicationAnswer> answers = new ArrayList<>();
}