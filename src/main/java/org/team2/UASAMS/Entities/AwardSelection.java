package org.team2.UASAMS.Entities;

import java.time.LocalDateTime;

import org.team2.UASAMS.Entities.Enums.AwardSelectionStatus;

import jakarta.persistence.*;
import lombok.*;

/**
 * Represents a final scholarship award decision for a winning application within the UASAMS system.
 * <p>
 * Tracks the decision timestamp, current award status, and the designated panel user who approved
 * or recorded the selection for a specific {@link Application} and {@link Scholarship}.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link Application} – The winning application selected for the award</li>
 *   <li>{@link Scholarship} – The scholarship being awarded</li>
 *   <li>{@link User} – The designated panel user responsible for the award decision</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class AwardSelection {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Date and time when the award selection decision was made.
     */
    private LocalDateTime decisionDate;

    /**
     * Current status of the award (e.g., "SELECTED", "ACCEPTED", "DECLINED", "DISBURSED").
     */
    @Enumerated(EnumType.STRING)
    private AwardSelectionStatus status;

    /**
     * The application that was selected for this award.
     */
    @OneToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "application_id", nullable = false, unique = true)
    private Application application;

    /**
     * The scholarship from which the award is granted.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "scholarship_id", nullable = false)
    private Scholarship scholarship;

    /**
     * The panel member or administrator who finalized the selection.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "designated_panel_user_id", nullable = false)
    private User designatedPanelUser;
}