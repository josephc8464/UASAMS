package org.team2.UASAMS.Entities;

import java.util.ArrayList;
import java.util.Collection;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;

import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;
import org.team2.UASAMS.Entities.Enums.UserRole;

import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Represents a base system user account within the UASAMS system.
 * <p>
 * Implements Spring Security's {@link UserDetails} to handle authentication and role-based
 * authorization. Uses {@link InheritanceType#JOINED} so specialized accounts like
 * {@link StudentUser} extend this base table with additional profile fields.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link StudentUser} – Subclass extending this user with student-specific academic details</li>
 *   <li>{@link ApplicationReview} – Reviews conducted by this user as a committee member</li>
 *   <li>{@link AwardSelection} – Final award decisions recorded by this user</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
@Table(name = "users")
@Inheritance(strategy = InheritanceType.JOINED)
public class User implements UserDetails {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * User's legal or preferred first name.
     */
    private String firstName;

    /**
     * User's last name.
     */
    private String lastName;

    /**
     * Indicates whether the account is active and permitted to log in.
     */
    private boolean enabled;

    /**
     * Unique display username for the account.
     */
    @Column(unique = true)
    @NotNull 
    private String username;

    /**
     * Unique email address used as the primary login identifier for Spring Security.
     */
    @Column(unique = true)
    @NotNull 
    private String email;

    /**
     * BCrypt-hashed password used for authentication.
     */
    @NotBlank 
    @NotEmpty 
    @NotNull 
    private String password;

    /**
     * Security roles assigned to this user (e.g., STUDENT, REVIEWER, ADMIN).
     */
    @ElementCollection(targetClass = UserRole.class, fetch = FetchType.EAGER)
    @Enumerated(EnumType.STRING)
    private Set<UserRole> roles = new HashSet<>();

    /**
     * Application reviews submitted by this user.
     */
    @OneToMany(mappedBy = "reviewer")
    private List<ApplicationReview> conductedReviews = new ArrayList<>();

    /**
     * Scholarship award selections finalized by this user.
     */
    @OneToMany(mappedBy = "designatedPanelUser")
    private List<AwardSelection> decidedAwards = new ArrayList<>();
    
    /**
     * Returns the user's email address as the Spring Security authentication principal.
     *
     * @return the user's email address
     */
    @Override
    public String getUsername() {
        return this.email;
    }

    /**
     * Returns the hashed password used to authenticate the user.
     *
     * @return the encoded password
     */
    @Override
    public String getPassword() {
        return this.password;
    }
    
    /**
     * Converts the user's {@link UserRole} set into Spring Security {@link GrantedAuthority} objects.
     *
     * @return collection of granted authorities
     */
    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return roles.stream()
                .map(role -> new SimpleGrantedAuthority(role.name()))
                .collect(Collectors.toList());
    }

    /**
     * Indicates whether the user's account is enabled.
     *
     * @return {@code true} if the account is active, {@code false} otherwise
     */
    @Override
    public boolean isEnabled() {
        return this.enabled;
    }

    /**
     * Assigns an additional {@link UserRole} to this user.
     *
     * @param role the role to add
     */
    public void addRole(UserRole role) {
        this.roles.add(role);
    }
}