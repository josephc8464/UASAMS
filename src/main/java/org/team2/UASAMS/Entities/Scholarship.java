package org.team2.UASAMS.Entities;

import jakarta.persistence.*;
import lombok.*;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

import org.team2.UASAMS.Entities.Enums.Major;
import org.team2.UASAMS.Entities.Enums.ScholarshipStatus;

/**
 * Represents a scholarship opportunity available to students within the UASAMS system.
 * <p>
 * Stores the scholarship's title, description, award amount, eligible majors, application deadline,
 * disbursement details, and current status. Connects to its custom application questions, submitted
 * student applications, and final award selections.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link ScholarshipQuestion} – Custom prompt questions required for this scholarship</li>
 *   <li>{@link Application} – Student applications submitted for this scholarship</li>
 *   <li>{@link AwardSelection} – Final award decisions made for this scholarship</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class Scholarship {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Official title of the scholarship.
     */
    private String name;

    /**
     * Detailed overview of the scholarship, eligibility criteria, and expectations.
     */
    @Column(columnDefinition = "TEXT")
    private String description;

    /**
     * Dollar amount awarded to a selected recipient.
     */
    private float awardAmount;

    /**
     * Email or contact details for the scholarship sponsor or coordinator.
     */
    private String providerContact;

    /**
     * Academic majors eligible to apply for this scholarship.
     */
    @ElementCollection(targetClass = Major.class)
    @Enumerated(EnumType.STRING)
    private List<Major> eligibleMajors = new ArrayList<>();

    /**
     * Cutoff date and time for submitting an application.
     */
    private LocalDateTime deadline;

    /**
     * Instructions explaining how and when awarded funds are distributed.
     */
    @Column(columnDefinition = "TEXT")
    private String disbursementInstructions;

    /**
     * Current lifecycle state of the scholarship (e.g., DRAFT, OPEN, CLOSED, ARCHIVED).
     */
    @Enumerated(EnumType.STRING)
    private ScholarshipStatus status;

    /**
     * Custom application questions attached to this scholarship.
     */
    @OneToMany(mappedBy = "scholarship", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<ScholarshipQuestion> questions = new ArrayList<>();

    /**
     * All student applications submitted to this scholarship.
     */
    @OneToMany(mappedBy = "scholarship")
    private List<Application> applications = new ArrayList<>();

    /**
     * Final award selections granted under this scholarship.
     */
    @OneToMany(mappedBy = "scholarship")
    private List<AwardSelection> awardSelections = new ArrayList<>();
}