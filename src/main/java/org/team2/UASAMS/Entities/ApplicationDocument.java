package org.team2.UASAMS.Entities;

import java.time.LocalDateTime;
import jakarta.persistence.*;
import lombok.*;

/**
 * Represents a supporting document uploaded as part of a student's application within the UASAMS system.
 * <p>
 * Stores the file's metadata—such as its original display name, unique disk identifier, storage path,
 * MIME type, and upload timestamp—while the actual file bytes live on disk or external storage.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link Application} – The application this document was uploaded for</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class ApplicationDocument {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Original filename shown to users (e.g., "transcript.pdf").
     */
    @Column(nullable = false)
    private String fileName;

    /**
     * UUID-prefixed filename stored on disk to prevent naming collisions (e.g., "9f8e7d_transcript.pdf").
     */
    @Column(nullable = false, unique = true)
    private String storedFileName;

    /**
     * Full or relative directory path where the file is saved.
     */
    @Column(nullable = false)
    private String filePath;

    /**
     * MIME content type of the uploaded file (e.g., "application/pdf").
     */
    @Column(nullable = false)
    private String contentType;

    /**
     * File size in bytes.
     */
    private Long fileSize;

    /**
     * Category label for the document (e.g., "TRANSCRIPT", "RESUME").
     */
    private String documentType;

    /**
     * Date and time when the document was uploaded.
     */
    @Column(nullable = false)
    private LocalDateTime uploadTime;

    /**
     * The application this document belongs to.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    private Application application;

    /**
     * Sets {@link #uploadTime} to the current timestamp before initial save if not already set.
     */
    @PrePersist
    protected void onCreate() {
        if (this.uploadTime == null) {
            this.uploadTime = LocalDateTime.now();
        }
    }
}