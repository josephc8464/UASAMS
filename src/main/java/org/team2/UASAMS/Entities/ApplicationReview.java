package org.team2.UASAMS.Entities;

import java.time.LocalDateTime;

import jakarta.persistence.*;
import lombok.*;

/**
 * Represents a reviewer's evaluation of a scholarship application within the UASAMS system.
 * <p>
 * Stores the numeric rating, written feedback, and timestamp for a review submitted by a committee
 * member or administrator on a specific {@link Application}.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link Application} – The application being reviewed</li>
 *   <li>{@link User} – The reviewer who submitted the score and feedback</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class ApplicationReview {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Numeric score assigned to the application by the reviewer.
     */
    private int rating;

    /**
     * Written feedback or notes explaining the reviewer's evaluation.
     */
    @Column(columnDefinition = "TEXT")
    private String comments;

    /**
     * Date and time when the review was submitted or last updated.
     */
    private LocalDateTime reviewDateTime;

    /**
     * The application being evaluated.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "application_id", nullable = false)
    private Application application;

    /**
     * The user account of the reviewer who wrote this evaluation.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "reviewer_user_id", nullable = false)
    private User reviewer;
}