package org.team2.UASAMS.Entities;

import jakarta.persistence.*;
import lombok.*;

/**
 * Represents a student's response to a single scholarship question within the UASAMS system.
 * <p>
 * Links a specific {@link ScholarshipQuestion} to the {@link Application} it was answered on,
 * storing the student's text or selected value.
 * </p>
 *
 * <p><b>Key Relationships:</b></p>
 * <ul>
 *   <li>{@link Application} – The application this answer was submitted with</li>
 *   <li>{@link ScholarshipQuestion} – The prompt or question being answered</li>
 * </ul>
 *
 * @author Team 2
 * @since 11/25/26
 */
@Entity
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class ApplicationAnswer {

    /**
     * Primary key generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The student's submitted response to the question.
     */
    @Column(columnDefinition = "TEXT")
    private String answerValue;

    /**
     * The application this answer belongs to.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "application_id", nullable = false)
    private Application application;

    /**
     * The scholarship question that this answer responds to.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "question_id", nullable = false)
    private ScholarshipQuestion question;
}